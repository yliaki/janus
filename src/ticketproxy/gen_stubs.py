#!/usr/bin/env python3
"""Generate the jump-table half of the ticket proxy DLL from a steam_api64.dll.

    gen_stubs.py <out_stubs.c> <out.def> <override,...> <steam_api64.dll> ...

The export list is the union over all given DLLs (Goldberg's regular and debug
builds differ slightly); a name the loaded DLL lacks resolves to a stub that
returns 0.

Every function export becomes a 6-byte `jmp *janus_tbl[i]` stub; proxy.c fills
janus_tbl from the real (Goldberg) DLL in DllMain. Data exports (no code to
jump through) become PE forwarders. Names listed as overrides are left to
proxy.c, which defines them itself.
"""
import struct
import sys


def pe_exports(path):
    """[(name, is_code)] for every named export."""
    data = open(path, 'rb').read()
    pe = struct.unpack_from('<I', data, 0x3c)[0]
    if data[pe:pe + 4] != b'PE\0\0':
        raise SystemExit(f'{path}: not a PE file')
    nsec, = struct.unpack_from('<H', data, pe + 6)
    optsz, = struct.unpack_from('<H', data, pe + 20)
    opt = pe + 24
    if struct.unpack_from('<H', data, opt)[0] != 0x20b:
        raise SystemExit(f'{path}: not PE32+ (64-bit)')
    exp_rva, = struct.unpack_from('<I', data, opt + 112)
    secs = []
    for i in range(nsec):
        s = opt + optsz + 40 * i
        vsz, va, rsz, rptr = struct.unpack_from('<IIII', data, s + 8)
        chars, = struct.unpack_from('<I', data, s + 36)
        secs.append((va, max(vsz, rsz), rptr, chars))

    def off(rva):
        for va, sz, rptr, _ in secs:
            if va <= rva < va + sz:
                return rva - va + rptr
        raise ValueError(hex(rva))

    def is_code(rva):
        return any(va <= rva < va + sz and chars & 0x20000000   # MEM_EXECUTE
                   for va, sz, _, chars in secs)

    e = off(exp_rva)
    nfuncs, nnames, funcs, names, ords = struct.unpack_from('<IIIII', data, e + 20)
    out = []
    for i in range(nnames):
        name_off = off(struct.unpack_from('<I', data, off(names) + 4 * i)[0])
        name = data[name_off:data.index(b'\0', name_off)].decode()
        ordinal, = struct.unpack_from('<H', data, off(ords) + 2 * i)
        rva, = struct.unpack_from('<I', data, off(funcs) + 4 * ordinal)
        out.append((name, is_code(rva)))
    return out


def main():
    out_c, out_def, overrides, *dlls = sys.argv[1:]
    overrides = [o for o in overrides.split(',') if o]
    exports = list(dict.fromkeys(e for d in dlls for e in pe_exports(d)))
    funcs = [n for n, code in exports if code and n not in overrides]
    datas = [n for n, code in exports if not code and n not in overrides]
    with open(out_c, 'w') as f:
        f.write('/* Generated by gen_stubs.py — do not edit. */\n')
        f.write(f'#define JANUS_NSTUBS {len(funcs)}\n')
        f.write('void *janus_tbl[JANUS_NSTUBS];\n')
        f.write('const char *const janus_names[JANUS_NSTUBS] = {\n')
        f.writelines(f'    "{n}",\n' for n in funcs)
        f.write('};\n__asm__(".text\\n"\n')
        for i, n in enumerate(funcs):
            f.write(f'    ".globl {n}\\n{n}: jmp *janus_tbl+{8 * i}(%rip)\\n"\n')
        f.write(');\n')
    with open(out_def, 'w') as f:
        f.write('LIBRARY steam_api64.dll\nEXPORTS\n')
        f.writelines(f'    {n}\n' for n in funcs + overrides)
        f.writelines(f'    {n} = steam_api64_gbe.{n} DATA\n' for n in datas)
    print(f'{len(funcs)} stubs, {len(datas)} data forwarders, '
          f'{len(overrides)} overrides', file=sys.stderr)


if __name__ == '__main__':
    main()
